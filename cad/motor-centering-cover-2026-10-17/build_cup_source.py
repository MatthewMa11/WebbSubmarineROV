from pathlib import Path
r=Path(__file__).resolve().parent
s=(r/'native-before.fs').read_text(encoding='utf-8')
marker='// Finish the three pads generated by the native 4-instance circular pattern.'
assert s.count(marker)==1
s=s.replace(marker,(r/'centering_cup.fs').read_text(encoding='utf-8')+'\n\n'+marker)
call='        applyPhysicalPrintRevision(context,id+"physicalPrint",definition.nozzle);'
assert s.count(call)==1
s=s.replace(call,call+'\n        applyMotorCenteringCup(context,id+"centeringCup",definition.nozzle);')
assert s.count('FeatureScript 3095;')==1
(r/'thruster-centering-cup.fs').write_text(s,encoding='utf-8')
print('Built',len(s),'characters')
