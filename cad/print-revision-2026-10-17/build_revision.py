from pathlib import Path
r=Path(__file__).resolve().parent
source=(r/'native-before.fs').read_text()
start=source.index('    // A 10 mm closed wire tunnel, moved inward with a 4 mm rounded wall.')
end=source.index('    // Reinforce the existing hole locations',start)
source=source[:start]+'    // The single side collar is superseded by the continuous rear ring.\n\n'+source[end:]
marker='// Finish the three pads generated by the native 4-instance circular pattern.'
source=source.replace(marker,(r/'physical_revision.fs').read_text()+'\n\n'+marker)
call='        applyFinalPlaAssembly(context,id+"finalPla",definition.nozzle);'
assert source.count(call)==1
source=source.replace(call,call+'\n        applyPhysicalPrintRevision(context,id+"physicalPrint",definition.nozzle);')
assert source.count('FeatureScript 3095;')==1
(r/'thruster-physical-revision.fs').write_text(source)
print('Built',len(source),'characters')
